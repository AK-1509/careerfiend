// Copies prisma/migrations/*/migration.sql into src/migrations.generated.ts so a
// deployed dashboard (no repo checkout) can apply them. Run after changing the schema.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.join(import.meta.dirname, "..", "prisma", "migrations");
const list = readdirSync(dir)
  .filter((d) => existsSync(path.join(dir, d, "migration.sql")))
  .sort()
  .map((name) => ({ name, sql: readFileSync(path.join(dir, name, "migration.sql"), "utf8") }));
const out = `// Generated by scripts/embed-migrations.mjs from prisma/migrations. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(list, null, 2)};\n`;
writeFileSync(path.join(import.meta.dirname, "..", "src", "migrations.generated.ts"), out);
console.log(`Embedded ${list.length} migration(s).`);
