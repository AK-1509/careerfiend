import { collapseWhitespace, normalizeLabel, type NormalizedJob } from "@careerfiend/shared";
import { fromJson, toJson } from "@careerfiend/db";
import type { DemandMap, ProjectJobInput } from "@careerfiend/ai";
import { isFactualText, jobKeywords, mentions, surfaceForms } from "@careerfiend/matcher";
import { currentFacts, listSkills } from "@careerfiend/profile";
import type { AppContext } from "./context";
import { enqueue } from "./queue";
import { loadBank } from "./skill-bank";

/**
 * Skills to demonstrate: the skills, tools, processes and domain knowledge
 * your queued jobs ask for, aggregated across every listing you added, with
 * how many jobs ask for each and whether your résumé already shows it.
 *
 * The list is generated by the AI provider (it groups requirement lines from
 * different listings that ask for the same thing) and checked by code: every
 * item must cite real requirement ids, and its job count comes from those ids.
 * Without an AI provider, a keyword aggregation is used. Whether you already
 * show an item is decided deterministically at view time, so it follows your
 * résumé, confirmed skills and skill bank.
 */

const KEY = "demand.latest";
const MAX_JOBS = 60;
const MAX_REQUIREMENTS = 25;
const MAX_TEXT = 250;
/** New listings coalesce: the list is rebuilt this long after the last one arrives. */
const AUTO_DELAY_MS = 10 * 60_000;
const SKIP_KINDS = new Set(["degree", "license", "certification", "clearance", "location"]);

export interface DemandItem {
  name: string;
  kind: DemandMap["items"][number]["kind"];
  keywords: string[];
  jobIds: string[];
  requirementIds: string[];
  whyItMatters: string;
}

interface SavedDemand {
  generatedAt: string;
  method: "ai" | "keywords";
  jobIds: string[];
  jobs: { id: string; company: string; title: string }[];
  requirements: Record<string, string>;
  items: DemandItem[];
}

export type DemandStatus = "shown" | "transferable" | "not_shown";

export interface DemandView extends Omit<SavedDemand, "items"> {
  items: (DemandItem & { status: DemandStatus; evidence: string[] })[];
  /** Listings you added since the list was built. */
  newJobs: number;
}

/** The listings you added (the ones you queued), newest first. */
export async function demandJobs(ctx: AppContext): Promise<ProjectJobInput[]> {
  const rows = await ctx.db.job.findMany({ where: { endorsed: true }, orderBy: { createdAt: "desc" }, take: MAX_JOBS });
  return rows.map((j) => {
    const job = fromJson<NormalizedJob | null>(j.normalized, null);
    const requirements = (job?.requirements ?? [])
      .filter((r) => ["required", "preferred", "responsibility"].includes(r.category) && !SKIP_KINDS.has(r.kind))
      .slice(0, MAX_REQUIREMENTS)
      .map((r) => ({ id: r.id, text: r.text.slice(0, MAX_TEXT), category: r.category }));
    return { id: j.id, company: j.company, title: j.title, requirements };
  });
}

/** Keep items that cite real requirements; job counts come from those citations. */
export function validateDemand(map: DemandMap, jobs: ProjectJobInput[]): DemandItem[] {
  const reqToJob = new Map(jobs.flatMap((j) => j.requirements.map((r) => [r.id, j.id] as const)));
  const byName = new Map<string, DemandItem>();
  for (const raw of map.items) {
    const name = collapseWhitespace(raw.name).slice(0, 80);
    if (!name || isFactualText(name)) continue;
    const requirementIds = [...new Set(raw.requirementIds)].filter((id) => reqToJob.has(id));
    if (!requirementIds.length) continue;
    const keywords = [...new Set(raw.keywords.map((k) => collapseWhitespace(k).slice(0, 60)).filter(Boolean))].slice(0, 6);
    const k = normalizeLabel(name);
    const prev = byName.get(k);
    if (prev) {
      prev.requirementIds = [...new Set([...prev.requirementIds, ...requirementIds])];
      prev.jobIds = [...new Set(prev.requirementIds.map((id) => reqToJob.get(id)!))];
      prev.keywords = [...new Set([...prev.keywords, ...keywords])].slice(0, 8);
      continue;
    }
    byName.set(k, {
      name,
      kind: raw.kind,
      keywords,
      requirementIds,
      jobIds: [...new Set(requirementIds.map((id) => reqToJob.get(id)!))],
      whyItMatters: collapseWhitespace(raw.whyItMatters).slice(0, 300),
    });
  }
  return [...byName.values()].sort((a, b) => b.jobIds.length - a.jobIds.length || b.requirementIds.length - a.requirementIds.length);
}

/** Fallback without an AI provider: listing keywords, counted across jobs. */
async function keywordDemand(ctx: AppContext, jobs: ProjectJobInput[]): Promise<DemandItem[]> {
  const skills = await listSkills(ctx.db);
  const bank = await loadBank(ctx);
  const items = new Map<string, DemandItem>();
  for (const j of jobs) {
    const normalized = { requirements: j.requirements.map((r) => ({ ...r, kind: "skill", depth: "unspecified" })) } as unknown as NormalizedJob;
    for (const kw of jobKeywords(normalized, skills, bank)) {
      const reqIds = j.requirements.filter((r) => kw.forms.some((f) => mentions(r.text, f))).map((r) => r.id);
      if (!reqIds.length) continue;
      const k = normalizeLabel(kw.label);
      const item = items.get(k) ?? { name: kw.label, kind: "skill" as const, keywords: kw.forms.slice(0, 6), jobIds: [], requirementIds: [], whyItMatters: "" };
      item.jobIds = [...new Set([...item.jobIds, j.id])];
      item.requirementIds = [...new Set([...item.requirementIds, ...reqIds])];
      items.set(k, item);
    }
  }
  return [...items.values()].sort((a, b) => b.jobIds.length - a.jobIds.length).slice(0, 40);
}

/** Build and store the list from every listing you added. */
export async function generateDemandMap(ctx: AppContext): Promise<{ items: number; jobs: number; method: SavedDemand["method"] }> {
  const jobs = (await demandJobs(ctx)).filter((j) => j.requirements.length);
  let items: DemandItem[] = [];
  let method: SavedDemand["method"] = "keywords";
  if (jobs.length && ctx.ai.available) {
    try {
      items = validateDemand(await ctx.ai.mapDemand({ jobs }), jobs);
      method = "ai";
    } catch (err) {
      ctx.logger.warn("demand.ai_failed", { error: err });
    }
  }
  if (!items.length) {
    items = await keywordDemand(ctx, jobs);
    method = "keywords";
  }
  const saved: SavedDemand = {
    generatedAt: ctx.now().toISOString(),
    method,
    jobIds: jobs.map((j) => j.id),
    jobs: jobs.map((j) => ({ id: j.id, company: j.company, title: j.title })),
    requirements: Object.fromEntries(jobs.flatMap((j) => j.requirements.map((r) => [r.id, r.text]))),
    items,
  };
  await ctx.db.setting.upsert({ where: { key: KEY }, create: { key: KEY, value: toJson(saved) }, update: { value: toJson(saved) } });
  ctx.logger.info("demand.generated", { count: items.length, status: `${jobs.length} jobs (${method})` });
  return { items: items.length, jobs: jobs.length, method };
}

export async function requestDemandMap(ctx: AppContext): Promise<string> {
  await enqueue(ctx.db, "DEMAND_MAP", {}, { dedupeKey: "demand:pending" });
  return "Rebuilding your skills-to-demonstrate list from every job you added. It takes about a minute.";
}

/** After a new listing: rebuild once things settle (several pastes in a row cost one run). */
export async function scheduleDemandRefresh(ctx: AppContext): Promise<void> {
  await enqueue(ctx.db, "DEMAND_MAP", {}, { dedupeKey: "demand:auto", runAt: new Date(ctx.now().getTime() + AUTO_DELAY_MS) });
}

/** A rebuild is queued to run now (not a delayed automatic one). */
export async function demandBuilding(ctx: AppContext): Promise<boolean> {
  return (await ctx.db.workItem.count({ where: { kind: "DEMAND_MAP", status: { in: ["PENDING", "RUNNING"] }, runAt: { lte: ctx.now() } } })) > 0;
}

export async function demandMapExists(ctx: AppContext): Promise<boolean> {
  return !!(await ctx.db.setting.findUnique({ where: { key: KEY } }));
}

/** The stored list with, for each item, whether your résumé, confirmed skills or skill bank already show it. */
export async function demandView(ctx: AppContext): Promise<DemandView | null> {
  const row = await ctx.db.setting.findUnique({ where: { key: KEY } });
  const saved = row ? fromJson<SavedDemand | null>(row.value, null) : null;
  if (!saved) return null;
  const facts = (await currentFacts(ctx.db)).filter(
    (f) => f.kind === "responsibility" || f.kind === "summary" || f.kind === "skill" || f.key.endsWith(".endorsedSkills"),
  );
  const usable = (await listSkills(ctx.db)).filter((s) => s.status === "VERIFIED_FROM_SOURCE" || s.status === "CONFIRMED_BY_USER");
  const bank = (await loadBank(ctx)).filter((b) => b.kind === "skill" && b.evidenceKeys.length);
  const items = saved.items.map((item) => {
    const forms = [item.name, ...item.keywords];
    const hit = (text: string) => forms.some((f) => mentions(text, f));
    const fact = facts.find((f) => hit(f.text));
    if (fact) return { ...item, status: "shown" as const, evidence: [`Résumé: “${fact.text.slice(0, 140)}”`] };
    const skill = usable.find((s) => surfaceForms(s).some((sf) => hit(sf) || forms.some((f) => mentions(sf, f))));
    if (skill)
      return { ...item, status: "shown" as const, evidence: [`${skill.status === "CONFIRMED_BY_USER" ? "Confirmed" : "Résumé"} skill: ${skill.label}`] };
    const banked = bank.find((b) => hit(b.label) || forms.some((f) => mentions(b.label, f)));
    if (banked) return { ...item, status: "transferable" as const, evidence: [`Skill bank: ${banked.label} (linked to your experience)`] };
    return { ...item, status: "not_shown" as const, evidence: [] };
  });
  const newJobs = await ctx.db.job.count({ where: { endorsed: true, id: { notIn: saved.jobIds } } });
  return { ...saved, items, newJobs };
}

/** Names of the most-requested items your résumé does not show yet (to steer project ideas). */
export async function demandGaps(ctx: AppContext, limit = 10): Promise<string[]> {
  const view = await demandView(ctx);
  return (view?.items ?? [])
    .filter((i) => i.status === "not_shown")
    .slice(0, limit)
    .map((i) => i.name);
}
